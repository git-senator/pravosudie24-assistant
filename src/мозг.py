"""
Мозг — единая обёртка над моделями.

Переключается строкой МОДЕЛЬ в .env, код при этом не меняется:

    МОДЕЛЬ=gemini-3.6-flash     → Google Gemini (бесплатный тариф)
    МОДЕЛЬ=claude-haiku-4-5     → Anthropic Claude, дёшево
    МОДЕЛЬ=claude-opus-5        → Anthropic Claude, дорого и умно
    МОДЕЛЬ=заглушка             → ничего никуда не шлёт, для отладки

Наружу торчат две функции: классифицировать() для триажа лидов
и ответить() для диалога с клиентом.
"""

import json
import os
import time
from dataclasses import dataclass, field
from typing import Any

import httpx

from . import настройки

GEMINI_БАЗА = "https://generativelanguage.googleapis.com/v1beta/models"

# У бесплатного тарифа Gemini есть предел запросов в минуту. Упереться в
# него — обычное дело, а не поломка: надо просто подождать и повторить.
ПОВТОРОВ = 4
ПАУЗЫ = (5, 15, 40)  # секунд между попытками
ПОВТОРЯЕМЫЕ_КОДЫ = {429, 500, 502, 503, 504}

# Цены за миллион токенов: (вход, выход). Gemini на бесплатном тарифе — ноль.
ЦЕНЫ = {
    "claude-opus-5": (5.0, 25.0),
    "claude-haiku-4-5": (1.0, 5.0),
    "claude-sonnet-5": (3.0, 15.0),
}


@dataclass
class Ответ:
    """Что вернула модель."""

    текст: str = ""
    инструмент: str | None = None
    аргументы: dict[str, Any] = field(default_factory=dict)
    входных: int = 0
    выходных: int = 0
    модель: str = ""

    @property
    def доллары(self) -> float:
        вход, выход = ЦЕНЫ.get(self.модель, (0.0, 0.0))
        return self.входных / 1e6 * вход + self.выходных / 1e6 * выход


class ОшибкаМозга(RuntimeError):
    pass


# --- Триаж лида ----------------------------------------------------------

СХЕМА_ТРИАЖА = {
    "type": "object",
    "properties": {
        "это_запрос": {
            "type": "boolean",
            "description": "Человек сам ищет юридическую помощь прямо сейчас",
        },
        "категория": {
            "type": "string",
            "description": "ДТП, ЖКХ, недвижимость, потребитель, взыскание, "
                           "приставы, банкротство, наследство, уголовное, "
                           "арбитраж, другое",
        },
        "суть": {"type": "string", "description": "Проблема человека одной фразой"},
        "сумма": {"type": "string", "description": "Сумма спора, если названа, иначе пусто"},
        "почему": {"type": "string", "description": "Коротко: почему такое решение"},
    },
    "required": ["это_запрос", "категория", "суть", "почему"],
}

ПРОМПТ_ТРИАЖА = """Ты фильтр входящих сообщений для юридической компании.

Тебе дают сообщение из Telegram-чата. Реши одно: человек СЕЙЧАС ищет юриста
или юридическую помощь для СЕБЯ — да или нет.

это_запрос = true, если человек:
- просит порекомендовать юриста или адвоката
- описывает свою юридическую проблему и явно ищет помощь
- спрашивает, что делать в правовой ситуации, которая произошла с ним

это_запрос = false, если человек:
- обсуждает чужое дело, новость, закон вообще
- сам предлагает юридические услуги (это конкурент)
- шутит, ругается, спорит на правовую тему
- задаёт теоретический вопрос без своей ситуации
- рекламирует что-либо

Отвечай строго в JSON по заданной схеме, без пояснений вокруг."""


# --- Gemini --------------------------------------------------------------

def _сколько_ждать(ответ: httpx.Response, по_умолчанию: float) -> float:
    """Gemini часто сам подсказывает, через сколько повторять."""
    try:
        for деталь in ответ.json()["error"].get("details", []):
            задержка = деталь.get("retryDelay")
            if задержка:
                return float(str(задержка).rstrip("s")) + 1
    except Exception:
        pass
    return по_умолчанию


def _gemini_запрос(модель: str, тело: dict) -> dict:
    ключ = настройки.GEMINI_КЛЮЧ
    if not ключ:
        raise ОшибкаМозга("GEMINI_API_KEY пуст")
    url = f"{GEMINI_БАЗА}/{модель}:generateContent?key={ключ}"

    беда = "неизвестно что"
    сделано = 0
    for попытка in range(ПОВТОРОВ):
        сделано += 1
        пауза = ПАУЗЫ[min(попытка, len(ПАУЗЫ) - 1)]
        повторить = False

        try:
            ответ = httpx.post(url, json=тело, timeout=120)
        except httpx.HTTPError as e:
            беда, повторить = f"сеть: {e}", True
        else:
            if ответ.status_code == 200:
                return ответ.json()
            беда = f"{ответ.status_code}: {ответ.text[:300]}"
            if ответ.status_code in ПОВТОРЯЕМЫЕ_КОДЫ:
                повторить = True
                пауза = _сколько_ждать(ответ, пауза)

        if not повторить or попытка == ПОВТОРОВ - 1:
            break

        print(f"   (модель занята, жду {пауза:.0f} с и пробую снова)")
        time.sleep(пауза)

    сколько = "с первого раза" if сделано == 1 else f"после {сделано} попыток"
    raise ОшибкаМозга(f"Gemini не ответил {сколько} — {беда}")


def _gemini_разобрать(данные: dict, модель: str) -> Ответ:
    исп = данные.get("usageMetadata", {})
    итог = Ответ(
        модель=модель,
        входных=исп.get("promptTokenCount", 0),
        выходных=исп.get("candidatesTokenCount", 0),
    )

    кандидаты = данные.get("candidates") or []
    if not кандидаты:
        return итог

    for часть in кандидаты[0].get("content", {}).get("parts", []):
        if "text" in часть:
            итог.текст += часть["text"]
        elif "functionCall" in часть:
            вызов = часть["functionCall"]
            итог.инструмент = вызов.get("name")
            итог.аргументы = вызов.get("args") or {}

    return итог


# --- Claude --------------------------------------------------------------

def _claude_клиент():
    import anthropic

    ключ = настройки.ANTHROPIC_КЛЮЧ
    if not ключ:
        raise ОшибкаМозга("ANTHROPIC_API_KEY пуст")
    return anthropic.Anthropic(api_key=ключ)


def _claude_разобрать(сообщение, модель: str) -> Ответ:
    итог = Ответ(
        модель=модель,
        входных=сообщение.usage.input_tokens,
        выходных=сообщение.usage.output_tokens,
    )
    for блок in сообщение.content:
        if блок.type == "text":
            итог.текст += блок.text
        elif блок.type == "tool_use":
            итог.инструмент = блок.name
            итог.аргументы = dict(блок.input)
    return итог


# --- Общий вход ----------------------------------------------------------

def классифицировать(текст: str, чат: str = "") -> dict[str, Any]:
    """Триаж одного сообщения. Возвращает разобранный JSON."""
    модель = настройки.МОДЕЛЬ_ТРИАЖА
    ввод = f"Чат: {чат}\nСообщение: {текст}"

    if модель == "заглушка":
        return {
            "это_запрос": True,
            "категория": "другое",
            "суть": текст[:80],
            "сумма": "",
            "почему": "режим заглушки — модель не вызывалась",
            "_заглушка": True,
        }

    if модель.startswith("gemini"):
        данные = _gemini_запрос(
            модель,
            {
                "systemInstruction": {"parts": [{"text": ПРОМПТ_ТРИАЖА}]},
                "contents": [{"role": "user", "parts": [{"text": ввод}]}],
                "generationConfig": {
                    "responseMimeType": "application/json",
                    "responseSchema": СХЕМА_ТРИАЖА,
                    "temperature": 0,
                },
            },
        )
        ответ = _gemini_разобрать(данные, модель)
    else:
        клиент = _claude_клиент()
        сообщение = клиент.messages.create(
            model=модель,
            max_tokens=1024,
            system=ПРОМПТ_ТРИАЖА,
            output_config={"format": {"type": "json_schema", "schema": СХЕМА_ТРИАЖА}},
            messages=[{"role": "user", "content": ввод}],
        )
        ответ = _claude_разобрать(сообщение, модель)

    try:
        итог = json.loads(ответ.текст)
    except json.JSONDecodeError as e:
        raise ОшибкаМозга(f"модель вернула не JSON: {ответ.текст[:200]}") from e

    итог["_входных"] = ответ.входных
    итог["_выходных"] = ответ.выходных
    итог["_доллары"] = ответ.доллары
    return итог


def ответить(
    системный: str,
    история: list[dict[str, str]],
    инструменты: list[dict] | None = None,
) -> Ответ:
    """
    Один ход диалога.

    история — список {"роль": "клиент"|"ассистент", "текст": "..."}
    инструменты — описания в общем виде: {"имя", "описание", "поля"}
    """
    модель = настройки.МОДЕЛЬ

    if модель == "заглушка":
        return Ответ(текст="[заглушка] Модель не вызывалась.", модель=модель)

    if модель.startswith("gemini"):
        тело: dict[str, Any] = {
            "systemInstruction": {"parts": [{"text": системный}]},
            "contents": [
                {
                    "role": "user" if х["роль"] == "клиент" else "model",
                    "parts": [{"text": х["текст"]}],
                }
                for х in история
            ],
            "generationConfig": {"temperature": 0.7},
        }
        if инструменты:
            тело["tools"] = [
                {
                    "functionDeclarations": [
                        {
                            "name": и["имя"],
                            "description": и["описание"],
                            "parameters": {
                                "type": "object",
                                "properties": и["поля"],
                                "required": и.get("обязательные", []),
                            },
                        }
                        for и in инструменты
                    ]
                }
            ]
        return _gemini_разобрать(_gemini_запрос(модель, тело), модель)

    клиент = _claude_клиент()
    параметры: dict[str, Any] = {
        "model": модель,
        "max_tokens": 2048,
        "system": системный,
        "messages": [
            {
                "role": "user" if х["роль"] == "клиент" else "assistant",
                "content": х["текст"],
            }
            for х in история
        ],
    }
    if инструменты:
        параметры["tools"] = [
            {
                "name": и["имя"],
                "description": и["описание"],
                "input_schema": {
                    "type": "object",
                    "properties": и["поля"],
                    "required": и.get("обязательные", []),
                },
            }
            for и in инструменты
        ]
    return _claude_разобрать(клиент.messages.create(**параметры), модель)
