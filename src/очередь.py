"""
Очередь первых сообщений.

Слушатель находит людей быстрее, чем им можно писать. Очередь решает,
кому и когда уходит ПЕРВОЕ сообщение — это защита аккаунта от блокировки.

Ответы в уже начатых диалогах через очередь не идут: там мы отвечаем
человеку, который написал нам сам, и лимиты не нужны.
"""

import random
from datetime import datetime, timedelta, timezone
from zoneinfo import ZoneInfo

from . import настройки
from .картотека import В_ОЧЕРЕДИ, НОВЫЙ, Картотека


class Решение:
    def __init__(self, можно: bool, причина: str = "", ждать_сек: int = 0):
        self.можно = можно
        self.причина = причина
        self.ждать_сек = ждать_сек

    def __bool__(self) -> bool:
        return self.можно


def местное_время() -> datetime:
    try:
        зона = ZoneInfo(настройки.ЧАСОВОЙ_ПОЯС)
    except Exception:
        зона = timezone.utc
    return datetime.now(зона)


def сейчас_тихий_час() -> bool:
    час = местное_время().hour
    с, до = настройки.ТИХО_С, настройки.ТИХО_ДО
    if с == до:
        return False
    if с < до:                 # например с 2 до 9
        return с <= час < до
    return час >= с or час < до  # через полночь: с 22 до 9


class Очередь:
    def __init__(self, картотека: Картотека):
        self.картотека = картотека

    def можно_писать_первым(self) -> Решение:
        """Проверяет все ограничения разом. Порядок — от грубых к тонким."""

        if сейчас_тихий_час():
            return Решение(
                False,
                f"тихий час ({настройки.ТИХО_С}:00–{настройки.ТИХО_ДО}:00 "
                f"{настройки.ЧАСОВОЙ_ПОЯС}, сейчас {местное_время():%H:%M})",
            )

        потрачено = self.картотека.потрачено_за_сутки()
        if потрачено >= настройки.ЛИМИТ_ТРАТ_В_СУТКИ:
            return Решение(
                False,
                f"упёрлись в лимит трат: ${потрачено:.2f} из "
                f"${настройки.ЛИМИТ_ТРАТ_В_СУТКИ}",
            )

        за_сутки = self.картотека.первых_за_период(24)
        if за_сутки >= настройки.ПЕРВЫХ_В_СУТКИ:
            return Решение(
                False, f"суточный лимит: {за_сутки} из {настройки.ПЕРВЫХ_В_СУТКИ}"
            )

        за_час = self.картотека.первых_за_период(1)
        if за_час >= настройки.ПЕРВЫХ_В_ЧАС:
            return Решение(
                False, f"часовой лимит: {за_час} из {настройки.ПЕРВЫХ_В_ЧАС}"
            )

        осталось = self._сколько_ждать()
        if осталось > 0:
            return Решение(
                False, f"пауза между отправками, осталось {осталось // 60} мин",
                ждать_сек=осталось,
            )

        return Решение(True)

    def _сколько_ждать(self) -> int:
        """Сколько секунд осталось до конца паузы после прошлой отправки."""
        последняя = self.картотека.когда_последняя_первая()
        if not последняя:
            return 0
        try:
            было = datetime.fromisoformat(последняя)
        except ValueError:
            return 0
        if было.tzinfo is None:
            было = было.replace(tzinfo=timezone.utc)

        прошло = (datetime.now(timezone.utc) - было).total_seconds()
        нужно = random.randint(настройки.ПАУЗА_МИН_СЕК, настройки.ПАУЗА_МАКС_СЕК)
        осталось = int(нужно - прошло)
        return max(0, осталось)

    def следующий(self) -> dict | None:
        """Кому писать первым. Берёт самого свежего из новых."""
        новые = self.картотека.список(статус=НОВЫЙ, сколько=1)
        return новые[0] if новые else None

    def поставить_в_очередь(self, telegram_id: int) -> None:
        self.картотека.обновить(telegram_id, статус=В_ОЧЕРЕДИ)

    def пауза_до_следующей(self) -> int:
        """Случайная пауза — ровный интервал выдаёт робота."""
        return random.randint(настройки.ПАУЗА_МИН_СЕК, настройки.ПАУЗА_МАКС_СЕК)
