"""
Точка входа. Все команды программы собраны здесь.

    python -m src.main проверка   — проверить настройки, ничего не делать
    python -m src.main чаты       — показать, в каких чатах сидит слушатель
    python -m src.main скан       — пройти историю чатов и найти лидов
    python -m src.main слушать    — слушать чаты вживую
    python -m src.main лиды       — показать найденных
"""

import asyncio
import sys

from . import настройки
from .картотека import Картотека
from .слушатель import Слушатель, описание_чата, не_группа


def команда_проверка() -> int:
    print("=== настройки ===")
    print(f"модель диалогов: {настройки.МОДЕЛЬ}")
    print(f"модель триажа:   {настройки.МОДЕЛЬ_ТРИАЖА}")
    print(f"режим репетиции: {'ДА — наружу ничего не уходит' if настройки.РЕПЕТИЦИЯ else 'НЕТ — боевой режим'}")
    print(f"первых в час:    {настройки.ПЕРВЫХ_В_ЧАС}")
    print(f"первых в сутки:  {настройки.ПЕРВЫХ_В_СУТКИ}")
    print(f"тишина:          с {настройки.ТИХО_С}:00 до {настройки.ТИХО_ДО}:00 ({настройки.ЧАСОВОЙ_ПОЯС})")
    print(f"лимит трат:      ${настройки.ЛИМИТ_ТРАТ_В_СУТКИ}/сутки")
    print(f"почтовый ящик:   @{настройки.ЯЩИК_USERNAME or '—'}")

    беды = настройки.проверить()
    print("\n=== проблемы ===")
    if беды:
        for б in беды:
            print(f"  ✗ {б}")
        return 1
    print("  нет, всё заполнено")

    from .слушатель import загрузить_слова

    слова = загрузить_слова()
    print(f"\nключевых слов загружено: {len(слова)}")

    к = Картотека()
    сводка = к.сводка_по_статусам()
    print(f"в картотеке: {sum(сводка.values())} человек {сводка or ''}")
    к.закрыть()
    return 0


async def команда_чаты() -> int:
    from telethon import TelegramClient

    акк = настройки.СЛУШАТЕЛЬ
    client = TelegramClient(акк.сессия, акк.api_id, акк.api_hash)
    await client.start()

    групп = 0
    print("=== чаты слушателя ===")
    async for диалог in client.iter_dialogs():
        if не_группа(диалог):
            continue
        групп += 1
        участников = getattr(диалог.entity, "participants_count", None) or "?"
        print(f"  {диалог.name}  (участников: {участников})")

    if групп == 0:
        print("  пусто — слушателю нечего читать")
        print("  вступи с аккаунта @RiDiK_51 в группы, где ищут юристов")
    else:
        print(f"\nвсего групп и каналов: {групп}")

    await client.disconnect()
    return 0


async def команда_скан(сколько: int) -> int:
    к = Картотека()
    с = Слушатель(к)
    await с.просканировать(сколько_на_чат=сколько)
    к.закрыть()
    return 0


async def команда_слушать() -> int:
    к = Картотека()
    с = Слушатель(к)
    try:
        await с.слушать()
    finally:
        с.напечатать_итог()
        к.закрыть()
    return 0


def команда_лиды(сколько: int) -> int:
    к = Картотека()
    люди = к.список(сколько=сколько)

    if not люди:
        print("Картотека пуста. Запусти 'скан' или 'слушать'.")
        к.закрыть()
        return 0

    print(f"=== найдено: {len(люди)} ===\n")
    for ч in люди:
        ник = f"@{ч['username']}" if ч["username"] else "(без username)"
        print(f"[{ч['статус']}] {ч['имя'] or '—'} {ник}")
        print(f"    чат:       {ч['чат_источник']}")
        print(f"    категория: {ч['категория'] or '—'}")
        print(f"    суть:      {ч['суть'] or '—'}")
        if ч["сумма"]:
            print(f"    сумма:     {ч['сумма']}")
        print(f"    написал:   {(ч['исходный_текст'] or '')[:160]}")
        print()

    print("--- по статусам ---")
    for статус, сколько_их in к.сводка_по_статусам().items():
        print(f"  {статус}: {сколько_их}")
    к.закрыть()
    return 0


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    команда = sys.argv[1]
    число = int(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2].isdigit() else None

    if команда == "проверка":
        sys.exit(команда_проверка())
    if команда == "чаты":
        sys.exit(asyncio.run(команда_чаты()))
    if команда == "скан":
        sys.exit(asyncio.run(команда_скан(число or 200)))
    if команда == "слушать":
        sys.exit(asyncio.run(команда_слушать()))
    if команда == "лиды":
        sys.exit(команда_лиды(число or 50))

    print(__doc__)
    sys.exit(1)


if __name__ == "__main__":
    main()
