"""
Точка входа. Все команды программы собраны здесь.

    python -m src.main проверка   — проверить настройки, ничего не делать
    python -m src.main чаты       — показать, в каких чатах сидит слушатель
    python -m src.main скан       — пройти историю чатов и найти лидов
    python -m src.main лиды       — показать найденных
    python -m src.main сводка     — прислать итоги за сутки в почтовый ящик
    python -m src.main забыть @ник        — стереть человека из картотеки
    python -m src.main забыть @ник совсем — и сам диалог в Telegram тоже
    python -m src.main слушать    — только слушатель, вживую
    python -m src.main ассистент  — только ассистент, отвечает на личку
    python -m src.main работать   — всё вместе: слушает, пишет первым, ведёт диалоги
"""

import asyncio
import sys

from . import настройки
from .ассистент import Ассистент
from .картотека import Картотека
from .очередь import Очередь
from .слушатель import Слушатель, не_группа


def команда_проверка() -> int:
    print("=== настройки ===")
    print(f"модель диалогов: {настройки.МОДЕЛЬ}")
    print(f"модель триажа:   {настройки.МОДЕЛЬ_ТРИАЖА}")
    режим = "ДА — наружу ничего не уходит" if настройки.РЕПЕТИЦИЯ else "НЕТ — БОЕВОЙ РЕЖИМ"
    print(f"режим репетиции: {режим}")
    print(f"первых в час:    {настройки.ПЕРВЫХ_В_ЧАС}")
    print(f"первых в сутки:  {настройки.ПЕРВЫХ_В_СУТКИ}")
    print(f"тишина:          с {настройки.ТИХО_С}:00 до {настройки.ТИХО_ДО}:00 ({настройки.ЧАСОВОЙ_ПОЯС})")
    print(f"лимит трат:      ${настройки.ЛИМИТ_ТРАТ_В_СУТКИ}/сутки")
    print(f"почтовый ящик:   @{настройки.ЯЩИК_USERNAME or '—'}")
    if настройки.ТОЛЬКО_ЧАТЫ:
        print(f"слушаем ТОЛЬКО: {', '.join(настройки.ТОЛЬКО_ЧАТЫ)}")
    else:
        print("слушаем:         все чаты, где сидит Ридик")

    беды = настройки.проверить()
    print("\n=== проблемы ===")
    if беды:
        for б in беды:
            print(f"  ✗ {б}")
        return 1
    print("  нет, всё заполнено")

    from .слушатель import загрузить_слова

    print(f"\nключевых слов загружено: {len(загрузить_слова())}")

    к = Картотека()
    сводка = к.сводка_по_статусам()
    print(f"в картотеке: {sum(сводка.values())} человек {сводка or ''}")

    о = Очередь(к)
    решение = о.можно_писать_первым()
    print(f"писать первым сейчас: {'да' if решение else 'нет — ' + решение.причина}")
    к.закрыть()
    return 0


async def команда_чаты() -> int:
    from telethon import TelegramClient

    акк = настройки.СЛУШАТЕЛЬ
    client = TelegramClient(акк.сессия, акк.api_id, акк.api_hash)
    await client.start()

    групп = 0
    print("=== чаты слушателя ===")
    async for диалог in client.iter_dialogs():
        if не_группа(диалог):
            continue
        групп += 1
        участников = getattr(диалог.entity, "participants_count", None) or "?"
        print(f"  {диалог.name}  (участников: {участников})")

    if групп == 0:
        print("  пусто — слушателю нечего читать")
    else:
        print(f"\nвсего групп и каналов: {групп}")

    await client.disconnect()
    return 0


async def команда_скан(сколько: int) -> int:
    к = Картотека()
    await Слушатель(к).просканировать(сколько_на_чат=сколько)
    к.закрыть()
    return 0


async def команда_слушать() -> int:
    к = Картотека()
    с = Слушатель(к)
    try:
        await с.слушать()
    finally:
        с.напечатать_итог()
        к.закрыть()
    return 0


async def команда_ассистент() -> int:
    к = Картотека()
    а = Ассистент(к)
    try:
        await asyncio.gather(а.слушать(), а.догонять())
    finally:
        к.закрыть()
    return 0


async def команда_сводка() -> int:
    """Прислать итоги прямо сейчас, не дожидаясь вечера."""
    к = Картотека()
    а = Ассистент(к)
    данные = к.сводка_за_сутки()
    print("=== итоги за сутки ===")
    for ключ, значение in данные.items():
        print(f"  {ключ}: {значение}")
    await а.client.start()
    await а.уведомитель.сводка(данные)
    await а.client.disconnect()
    к.закрыть()
    return 0


async def _очередь_фоном(ассистент: Ассистент, очередь: Очередь) -> None:
    """Раз в минуту смотрит, можно ли написать кому-то первым."""
    while True:
        await asyncio.sleep(60)
        try:
            кандидат = очередь.следующий()
            if not кандидат:
                continue
            решение = очередь.можно_писать_первым()
            if not решение:
                print(f"[очередь] жду: {решение.причина}")
                continue
            await ассистент.написать_первым(кандидат)
        except Exception as e:
            print(f"[очередь] сбой: {e}")


async def команда_работать() -> int:
    беды = настройки.проверить()
    if беды:
        for б in беды:
            print(f"✗ {б}")
        return 1

    к = Картотека()
    слушатель = Слушатель(к, тихо=True)
    ассистент = Ассистент(к)
    очередь = Очередь(к)

    print("=== запуск ===")
    режим = "РЕПЕТИЦИЯ — наружу ничего не уходит" if настройки.РЕПЕТИЦИЯ else "БОЕВОЙ РЕЖИМ"
    print(f"режим: {режим}")
    print(f"модель: {настройки.МОДЕЛЬ}\n")

    await слушатель.client.start()
    await ассистент.client.start()

    задачи = [
        asyncio.create_task(слушатель.слушать()),
        asyncio.create_task(ассистент.слушать()),
        asyncio.create_task(_очередь_фоном(ассистент, очередь)),
        asyncio.create_task(ассистент.догонять()),
        asyncio.create_task(ассистент.отчитываться()),
    ]
    try:
        await asyncio.gather(*задачи)
    finally:
        for з in задачи:
            з.cancel()
        слушатель.напечатать_итог()
        к.закрыть()
    return 0


def команда_лиды(сколько: int) -> int:
    к = Картотека()
    люди = к.список(сколько=сколько)

    if not люди:
        print("Картотека пуста. Запусти 'скан' или 'работать'.")
        к.закрыть()
        return 0

    print(f"=== найдено: {len(люди)} ===\n")
    for ч in люди:
        ник = f"@{ч['username']}" if ч["username"] else "(без username)"
        print(f"[{ч['статус']}] {ч['имя'] or '—'} {ник}")
        print(f"    чат:       {ч['чат_источник']}")
        print(f"    категория: {ч['категория'] or '—'}")
        print(f"    суть:      {ч['суть'] or '—'}")
        if ч["сумма"]:
            print(f"    сумма:     {ч['сумма']}")
        print(f"    написал:   {(ч['исходный_текст'] or '')[:160]}")
        print()

    print("--- по статусам ---")
    for статус, сколько_их in к.сводка_по_статусам().items():
        print(f"  {статус}: {сколько_их}")
    print(f"потрачено за сутки: ${к.потрачено_за_сутки():.4f}")
    к.закрыть()
    return 0


async def команда_забыть(кого: str, и_чат: bool) -> int:
    """
    Стереть человека из картотеки: карточку, переписку, отправки.

    Нужно, если человек просит удалить свои данные, и удобно для повторных
    тестов — иначе слушатель считает его уже известным и молча пропускает.

    Слово «совсем» вторым аргументом убирает ещё и сам диалог в Telegram,
    у обеих сторон.
    """
    if not кого:
        print("Кого забыть? Например: забыть @ivanov   (или: забыть @ivanov совсем)")
        return 1

    к = Картотека()
    клиент = к.получить(int(кого)) if кого.isdigit() else к.найти_по_нику(кого)

    if not клиент:
        print(f"В картотеке нет «{кого}»")
        if not и_чат:
            к.закрыть()
            return 1
        # В базе пусто, но диалог в Telegram мог остаться — убираем и его
        а = Ассистент(к)
        await а.client.start()
        try:
            await а.client.delete_dialog(кого, revoke=True)
            print("Зато диалог в Telegram удалён, с обеих сторон.")
            код = 0
        except Exception as e:
            print(f"Диалог удалить не вышло: {e}")
            код = 1
        await а.client.disconnect()
        к.закрыть()
        return код

    telegram_id = клиент["telegram_id"]
    ник = f"@{клиент['username']}" if клиент["username"] else str(telegram_id)
    print(f"Стираю {ник} ({клиент['имя'] or '—'}), статус «{клиент['статус']}»")
    print(f"  вместе с перепиской: {к.сколько_сообщений(telegram_id)} сообщений")

    if и_чат:
        а = Ассистент(к)
        await а.client.start()
        try:
            await а.client.delete_dialog(telegram_id, revoke=True)
            print("  диалог в Telegram удалён, с обеих сторон")
        except Exception as e:
            print(f"  ! диалог в Telegram удалить не вышло: {e}")
        await а.client.disconnect()

    к.забыть(telegram_id)
    print("Готово. Слушатель снова увидит его как нового.")
    к.закрыть()
    return 0


КОМАНДЫ = {
    "проверка": lambda ч: команда_проверка(),
    "чаты": lambda ч: asyncio.run(команда_чаты()),
    "скан": lambda ч: asyncio.run(команда_скан(ч or 200)),
    "лиды": lambda ч: команда_лиды(ч or 50),
    "сводка": lambda ч: asyncio.run(команда_сводка()),
    "забыть": lambda ч: asyncio.run(
        команда_забыть(
            sys.argv[2] if len(sys.argv) > 2 else "",
            len(sys.argv) > 3 and sys.argv[3].lower() in ("совсем", "начисто"),
        )
    ),
    "слушать": lambda ч: asyncio.run(команда_слушать()),
    "ассистент": lambda ч: asyncio.run(команда_ассистент()),
    "работать": lambda ч: asyncio.run(команда_работать()),
}


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in КОМАНДЫ:
        print(__doc__)
        sys.exit(1)

    число = int(sys.argv[2]) if len(sys.argv) > 2 and sys.argv[2].isdigit() else None
    sys.exit(КОМАНДЫ[sys.argv[1]](число))


if __name__ == "__main__":
    main()
