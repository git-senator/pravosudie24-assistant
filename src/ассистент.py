def загрузить_скрипт() -> str:
    return настройки.ФАЙЛ_СКРИПТА.read_text(encoding="utf-8")


class Ассистент:
    def __init__(self, картотека: Картотека):
        self.картотека = картотека
        self.скрипт = загрузить_скрипт()
        акк = настройки.АССИСТЕНТ
        self.client = TelegramClient(акк.сессия, акк.api_id, акк.api_hash)
        self.уведомитель = Уведомитель(self.client)
        self.мои_сообщения: set[int] = set()  # id того, что отправили мы сами

    # --- отправка --------------------------------------------------------

    async def _адрес(self, telegram_id: int):
        """
        Кому слать. Асик мог никогда не видеть этого человека — тогда по
        голому id Telegram его не найдёт. Сначала пробуем @username,
        он ищется глобально; потом уже id.
        """
        клиент = self.картотека.получить(telegram_id) or {}
        ник = клиент.get("username")

        if ник:
            try:
                return await self.client.get_input_entity(ник)
            except Exception:
                pass

        try:
            return await self.client.get_input_entity(telegram_id)
        except Exception as e:
            raise ОшибкаОтправки(
                f"Асик не знает этого человека (id={telegram_id}, "
                f"username={ник or 'нет'}). Добавь @Asic_RF в ту же группу, "
                f"где сидит Ридик — тогда он увидит участников. Причина: {e}"
            ) from e

    async def отправить(self, telegram_id: int, текст: str, первое: bool = False) -> None:
        if настройки.РЕПЕТИЦИЯ:
            print(f"   [репетиция] НЕ отправлено {telegram_id}: {текст[:120]}")
        else:
            куда = await self._адрес(telegram_id)
            сообщение = await self.client.send_message(куда, текст)
            self.мои_сообщения.add(сообщение.id)
            print(f"   -> {telegram_id}: {текст[:120]}")

        self.картотека.записать_сообщение(telegram_id, "ассистент", текст)
        self.картотека.записать_отправку(telegram_id, первое=первое)

    # --- один ход диалога ------------------------------------------------

    def _история(self, telegram_id: int) -> list[dict[str, str]]:
        итог = []
        for с in self.картотека.переписка(telegram_id):
            роль = "клиент" if с["кто"] == "клиент" else "ассистент"
            итог.append({"роль": роль, "текст": с["текст"]})
        return итог

    def _системный(self, клиент: dict) -> str:
        шапка = [
            "## Про этого человека (для тебя, не показывай ему)",
            f"Нашли в чате: {клиент.get('чат_источник') or '—'}",
            f"Исходное сообщение: {клиент.get('исходный_текст') or '—'}",
        ]
        if клиент.get("категория"):
            шапка.append(f"Предполагаемая категория: {клиент['категория']}")
        if клиент.get("сумма"):
            шапка.append(f"Названная сумма: {клиент['сумма']}")
        шапка.append(
            "\nНе заставляй его повторять то, что он уже написал в чате."
        )
        return self.скрипт + "\n\n" + "\n".join(шапка)

    async def ответить_клиенту(self, telegram_id: int) -> None:
        клиент = self.картотека.получить(telegram_id)
        if not клиент:
            return

        if клиент["статус"] in (У_ЮРИСТА, ОТКАЗ, НА_ПАУЗЕ):
            print(f"   (молчу: статус {клиент['статус']})")
            return

        сколько = self.картотека.сколько_сообщений(telegram_id)
        if сколько >= настройки.СООБЩЕНИЙ_НА_КЛИЕНТА:
            print(f"   (упёрлись в лимит {настройки.СООБЩЕНИЙ_НА_КЛИЕНТА} сообщений)")
            await self._передать_юристу(
                telegram_id,
                {"summary": "диалог затянулся, нужен человек", "readiness": "средняя"},
                срочно=False,
            )
            return

        потрачено = self.картотека.потрачено_за_сутки()
        if потрачено >= настройки.ЛИМИТ_ТРАТ_В_СУТКИ:
            print(f"   (лимит трат: ${потрачено:.2f})")
            return

        try:
            ответ = мозг.ответить(
                self._системный(клиент), self._история(telegram_id), ИНСТРУМЕНТЫ
            )
        except мозг.ОшибкаМозга as e:
            print(f"   ! мозг не ответил: {e}")
            return

        if ответ.доллары:
            self.картотека.записать_расход(
                ответ.модель, ответ.входных, ответ.выходных, ответ.доллары
            )

        if ответ.инструмент:
            await self._выполнить(telegram_id, ответ.инструмент, ответ.аргументы)
        elif ответ.текст.strip():
            await self.отправить(telegram_id, ответ.текст.strip())
            self.картотека.обновить(telegram_id, статус=ВЕДЁТ_АССИСТЕНТ)

    # --- инструменты -----------------------------------------------------

    def _ответов_клиента(self, telegram_id: int) -> int:
        return sum(
            1 for с in self.картотека.переписка(telegram_id) if с["кто"] == "клиент"
        )

    async def _выполнить(self, telegram_id: int, имя: str, аргументы: dict) -> None:
        print(f"   [инструмент] {имя}: {аргументы}")

        try:
            if имя == "client_ready":
                # Страховка от преждевременной передачи: модель любит
                # выскочить после первого же ответа, а прогревать некому.
                ответов = self._ответов_клиента(telegram_id)
                срок = (аргументы.get("deadline") or "").strip().lower()
                горит = bool(аргументы.get("urgent")) and срок not in (
                    "", "не указан", "не указана", "нет", "срочно",
                )

                if ответов < МИНИМУМ_ОТВЕТОВ and not горит:
                    print(
                        f"   (рано: ответов клиента {ответов} из {МИНИМУМ_ОТВЕТОВ}, "
                        f"горящей даты нет — продолжаю разговор)"
                    )
                    await self._дособрать(telegram_id, аргументы)
                    return

                await self._передать_юристу(
                    telegram_id, аргументы, срочно=bool(аргументы.get("urgent"))
                )

            elif имя == "close_politely":
                прощание = (аргументы.get("farewell") or "").strip()
                if прощание:
                    await self.отправить(telegram_id, прощание)
                self.картотека.обновить(
                    telegram_id, статус=ОТКАЗ,
                    причина_закрытия=аргументы.get("reason", ""),
                )

            elif имя == "dont_know":
                ответ = (аргументы.get("reply") or "").strip()
                if ответ:
                    await self.отправить(telegram_id, ответ)
                self.картотека.обновить(telegram_id, статус=У_ЮРИСТА)
                await self.уведомитель.вопрос(
                    self.картотека.получить(telegram_id),
                    аргументы.get("question", ""),
                )

            elif имя == "pause":
                self.картотека.обновить(
                    telegram_id, статус=НА_ПАУЗЕ,
                    причина_закрытия=аргументы.get("reason", ""),
                )

            else:
                print(f"   ! неизвестный инструмент: {имя}")

        except ОшибкаОтправки as e:
            print(f"   ! {e}")

    async def _дособрать(self, telegram_id: int, собрано: dict) -> None:
        """
        Модель захотела передать юристу слишком рано. Возвращаем её в
        разговор: показываем, что уже известно, и просим спросить дальше.
        """
        пусто = ("", "не указана", "не указан", "нет", "неизвестно", "—")
        не_хватает = [
            подпись
            for ключ, подпись in (
                ("stage", "стадия дела: был ли суд, претензия, решение"),
                ("amount", "сумма — ущерб, долг или цена иска"),
                ("documents", "какие документы на руках"),
                ("wants", "чего человек хочет добиться"),
                ("region", "регион"),
            )
            if str(собрано.get(ключ, "")).strip().lower() in пусто
        ]

        подсказка = (
            "\n\n## Системная заметка (человеку не показывай)\n"
            "Ты попытался передать клиента юристу, но разговор ещё слишком "
            "короткий — человек почти ничего не рассказал.\n"
            "Не передавай сейчас. Задай ОДИН следующий вопрос по скрипту, "
            "живой и уместный, опираясь на то, что он уже сказал.\n"
        )
        if не_хватает:
            подсказка += "Ещё не выяснено:\n" + "\n".join(
                f"- {п}" for п in не_хватает
            )

        клиент = self.картотека.получить(telegram_id)
        try:
            ответ = мозг.ответить(
                self._системный(клиент) + подсказка,
                self._история(telegram_id),
            )
        except мозг.ОшибкаМозга as e:
            print(f"   ! мозг не ответил: {e}")
            return

        if ответ.доллары:
            self.картотека.записать_расход(
                ответ.модель, ответ.входных, ответ.выходных, ответ.доллары
            )

        текст = ответ.текст.strip()
        if текст:
            await self.отправить(telegram_id, текст)
            self.картотека.обновить(telegram_id, статус=ВЕДЁТ_АССИСТЕНТ)

    async def _передать_юристу(
        self, telegram_id: int, данные: dict, срочно: bool
    ) -> None:
        # Сначала попрощаться с человеком, иначе он остаётся в тишине
        прощание = (данные.get("reply") or "").strip()
        if not прощание:
            прощание = (
                "Понял вашу ситуацию. Передам юристу краткое описание того, "
                "что вы рассказали, чтобы вам не пришлось повторять всё сначала."
            )
        await self.отправить(telegram_id, прощание)

        self.картотека.обновить(
            telegram_id,
            статус=ГОТОВ,
            категория=данные.get("category"),
            суть=данные.get("summary"),
            сумма=данные.get("amount"),
            стадия=данные.get("stage"),
            регион=данные.get("region"),
        )
        клиент = self.картотека.получить(telegram_id)
        await self.уведомитель.карточка(клиент, данные, срочно=срочно)

    # --- первое сообщение ------------------------------------------------

    async def написать_первым(self, клиент: dict) -> None:
        telegram_id = клиент["telegram_id"]
        print(f"\n>>> первое сообщение: @{клиент['username'] or telegram_id}")

        try:
            ответ = мозг.ответить(self._системный(клиент), [
                {
                    "роль": "клиент",
                    "текст": (
                        "[Это не сообщение от человека, а команда тебе. "
                        "Напиши ему первое сообщение по правилам скрипта, "
                        "опираясь на то, что он написал в чате.]"
                    ),
                }
            ])
        except мозг.ОшибкаМозга as e:
            print(f"   ! мозг не ответил: {e}")
            return

        if ответ.доллары:
            self.картотека.записать_расход(
                ответ.модель, ответ.входных, ответ.выходных, ответ.доллары
            )

        текст = ответ.текст.strip()
        if not текст:
            print("   ! модель вернула пустоту")
            return

        try:
            await self.отправить(telegram_id, текст, первое=True)
        except ОшибкаОтправки as e:
            print(f"   ! {e}")
            # Чтобы очередь не долбилась в него вечно
            self.картотека.обновить(
                telegram_id, статус=НА_ПАУЗЕ, причина_закрытия="не удалось написать"
            )
            return

        self.картотека.обновить(telegram_id, статус=ВЕДЁТ_АССИСТЕНТ)

    # --- запуск ----------------------------------------------------------

    async def слушать(self) -> None:
        await self.client.start()
        я = await self.client.get_me()
        print(f"Ассистент @{я.username} на связи.")
        if настройки.РЕПЕТИЦИЯ:
            print("РЕЖИМ РЕПЕТИЦИИ: наружу ничего не уходит.\n")

        @self.client.on(events.NewMessage(incoming=True))
        async def _входящее(событие):
            if not событие.is_private:
                return
            автор = await событие.get_sender()
            if not isinstance(автор, User) or автор.bot:
                return

            текст = (событие.message.message or "").strip()
            if not текст:
                return

            if not self.картотека.есть(автор.id):
                # написал кто-то, кого мы не находили — заводим карточку
                self.картотека.добавить(
                    telegram_id=автор.id,
                    username=автор.username,
                    имя=" ".join(filter(None, [автор.first_name, автор.last_name])),
                    чат_источник="написал сам",
                    исходный_текст=текст,
                )

            print(f"\n<- @{автор.username or автор.id}: {текст[:120]}")
            self.картотека.записать_сообщение(автор.id, "клиент", текст)
            await self.ответить_клиенту(автор.id)

        @self.client.on(events.NewMessage(outgoing=True))
        async def _исходящее(событие):
            """Денис написал сам — ассистент замолкает по этому клиенту."""
            if not событие.is_private:
                return
            if событие.message.id in self.мои_сообщения:
                return  # это наше собственное сообщение

            кому = событие.message.peer_id
            telegram_id = getattr(кому, "user_id", None)
            if not telegram_id or not self.картотека.есть(telegram_id):
                return

            клиент = self.картотека.получить(telegram_id)
            if клиент["статус"] == У_ЮРИСТА:
                return

            self.картотека.обновить(telegram_id, статус=У_ЮРИСТА)
            self.картотека.записать_сообщение(
                telegram_id, "юрист", событие.message.message or ""
            )
            print(f"\n[перехват] Денис написал @{клиент['username'] or telegram_id} — молчу")

        await self.client.run_until_disconnected()
