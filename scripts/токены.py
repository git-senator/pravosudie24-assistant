"""
Сколько токенов стоит один разговор с клиентом.

Считает по-настоящему, через countTokens — этот вызов бесплатный и квоту
на запросы не тратит. Нужен, чтобы прикидывать счёт за модель не на глаз.

    python -m scripts.токены
"""

import httpx

from src import настройки
from src.ассистент import ИНСТРУМЕНТЫ, загрузить_скрипт

# Типичный разговор: он пишет, мы спрашиваем, и так до карточки
ПРИМЕР_ДИАЛОГА = [
    "Да, здравствуйте. Три недели назад в меня въехали сзади на светофоре",
    "Понял вас. Подскажите, ГИБДД оформляли или европротокол? Вину вторая сторона признала?",
    "Машина в ремонте, экспертиза насчитала 380 тысяч, страховая выплатила 140",
    "Разница существенная. Претензию в страховую уже направляли или пока нет?",
    "Пока ничего не начинал, в суд не подавал, претензию не писал",
    "А какие документы на руках — постановление, заключение эксперта, чеки?",
    "Есть европротокол, постановление ГИБДД, заключение эксперта и чеки из сервиса",
    "Понял. И чего хотите добиться — добрать со страховой или взыскать с виновника?",
]


def посчитать(текст: str) -> int:
    url = (
        f"https://generativelanguage.googleapis.com/v1beta/models/"
        f"{настройки.МОДЕЛЬ}:countTokens?key={настройки.GEMINI_КЛЮЧ}"
    )
    ответ = httpx.post(
        url, json={"contents": [{"parts": [{"text": текст}]}]}, timeout=60
    )
    ответ.raise_for_status()
    return ответ.json()["totalTokens"]


def main() -> None:
    скрипт = загрузить_скрипт()
    инструменты = str(ИНСТРУМЕНТЫ)

    т_скрипт = посчитать(скрипт)
    т_инструменты = посчитать(инструменты)
    постоянное = т_скрипт + т_инструменты

    print(f"Скрипт разговора:      {т_скрипт:>6} токенов")
    print(f"Описание инструментов: {т_инструменты:>6}")
    print(f"Итого постоянная часть:{постоянное:>6} — уходит в КАЖДОМ запросе\n")

    всего_вход = 0
    история = ""
    ходов = 0

    for i, реплика in enumerate(ПРИМЕР_ДИАЛОГА):
        история += реплика + "\n"
        if i % 2 == 0:  # ответ модели считаем после реплики клиента
            ходов += 1
            всего_вход += постоянное + посчитать(история)

    выход = посчитать("\n".join(ПРИМЕР_ДИАЛОГА[1::2])) + 400  # +карточка

    print(f"Разговор из {ходов} ходов:")
    print(f"  на вход суммарно:  {всего_вход:>7} токенов")
    print(f"  на выход примерно: {выход:>7}\n")

    # Цены за миллион токенов (вход, выход), проверены 12 августа 2026
    print(f"{'модель':<24}{'разговор':>10}{'20 в день':>12}{'100 в день':>12}")
    print("-" * 58)
    for имя, (вход, вых) in {
        "Gemini 3.1 Flash-Lite": (0.25, 1.50),
        "Claude Haiku 4.5": (1.00, 5.00),
        "Gemini 3.5 Flash": (1.50, 9.00),
        "Gemini 3.1 Pro": (2.00, 12.00),
        "Claude Sonnet 5": (3.00, 15.00),
        "Claude Opus 5": (5.00, 25.00),
    }.items():
        цена = всего_вход / 1e6 * вход + выход / 1e6 * вых
        print(
            f"{имя:<24}${цена:>8.4f}"
            f"${цена * 20 * 30:>10.0f}/мес"
            f"${цена * 100 * 30:>10.0f}/мес"
        )


if __name__ == "__main__":
    main()
