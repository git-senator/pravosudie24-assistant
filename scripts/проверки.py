def проверить_своих() -> None:
    print("\n[8] Свои аккаунты слушатель за клиентов не принимает")
    from src.слушатель import Слушатель

    к = новая_картотека()
    с = Слушатель(к, тихо=True)

    class Кто:
        def __init__(self, id, username):
            self.id = id
            self.username = username

    ящик = настройки.ЯЩИК_USERNAME or "no_justice77"
    проверить("почтовый ящик юриста — свой", с.свой(Кто(1, ящик.upper())))
    проверить("посторонний человек — не свой", not с.свой(Кто(2, "прохожий")))

    с.запомнить_своего(Кто(777, "Asic_RF"))
    проверить("ассистента после знакомства узнаём по нику", с.свой(Кто(999, "asic_rf")))
    проверить("и по номеру тоже", с.свой(Кто(777, None)))
    проверить("а чужие так и остаются чужими", not с.свой(Кто(888, "ivanov")))
    к.закрыть()


