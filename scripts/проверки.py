"""
Самопроверка механики: лимиты, тихий час, догонялка, заморозка аккаунта.

Ни Telegram, ни модель не участвуют — только логика программы. Проходит за
секунду и ничего не стоит, поэтому запускать можно после любой правки.

    python -m scripts.проверки
"""

import asyncio
import sys
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

from src import настройки, очередь as модуль_очереди
from src.картотека import (
    ВЕДЁТ_АССИСТЕНТ,
    ГОТОВ,
    НОВЫЙ,
    У_ЮРИСТА,
    Картотека,
    давность,
)

провалы: list[str] = []


def проверить(что: str, условие: bool, подробности: str = "") -> None:
    if условие:
        print(f"  ХОРОШО  {что}")
    else:
        провалы.append(что)
        print(f"  ПЛОХО   {что}   {подробности}")


def новая_картотека() -> Картотека:
    папка = Path(tempfile.mkdtemp(prefix="проверки-"))
    return Картотека(str(папка / "картотека.db"))


def положить_отправку(к: Картотека, часов_назад: float) -> None:
    к.db.execute(
        "INSERT INTO отправки (telegram_id, время, первое) VALUES (?,?,1)",
        (1, давность(часов_назад)),
    )
    к.db.commit()


def положить_сообщение(к: Картотека, кто: int, автор: str, часов_назад: float) -> None:
    к.db.execute(
        "INSERT INTO сообщения (telegram_id, кто, текст, время) VALUES (?,?,?,?)",
        (кто, автор, "текст", давность(часов_назад)),
    )
    к.db.commit()


# --- 1. Время в базе -----------------------------------------------------

def проверить_время() -> None:
    print("\n[1] Счёт времени в базе")
    к = новая_картотека()

    положить_отправку(к, часов_назад=5)
    проверить(
        "отправка пятичасовой давности НЕ считается сделанной за последний час",
        к.первых_за_период(1) == 0,
        f"насчитал {к.первых_за_период(1)}",
    )
    проверить(
        "она же считается сделанной за сутки",
        к.первых_за_период(24) == 1,
        f"насчитал {к.первых_за_период(24)}",
    )

    положить_отправку(к, часов_назад=0.2)
    проверить(
        "свежая отправка попадает в последний час",
        к.первых_за_период(1) == 1,
        f"насчитал {к.первых_за_период(1)}",
    )

    положить_отправку(к, часов_назад=30)
    проверить(
        "вчерашняя отправка в сутки уже не попадает",
        к.первых_за_период(24) == 2,
        f"насчитал {к.первых_за_период(24)}",
    )
    к.закрыть()


# --- 2. Лимиты первых сообщений -----------------------------------------

def проверить_лимиты() -> None:
    print("\n[2] Лимиты первых сообщений")
    было = модуль_очереди.сейчас_тихий_час
    модуль_очереди.сейчас_тихий_час = lambda: False  # тишину проверим отдельно
    try:
        к = новая_картотека()
        о = модуль_очереди.Очередь(к)

        проверить("на чистой картотеке писать можно", bool(о.можно_писать_первым()))

        for _ in range(настройки.ПЕРВЫХ_В_ЧАС):
            положить_отправку(к, часов_назад=0.1)
        решение = о.можно_писать_первым()
        проверить(
            f"после {настройки.ПЕРВЫХ_В_ЧАС} писем за час очередь останавливается",
            not решение and "часовой" in решение.причина,
            решение.причина,
        )

        к2 = новая_картотека()
        о2 = модуль_очереди.Очередь(к2)
        for _ in range(настройки.ПЕРВЫХ_В_СУТКИ):
            положить_отправку(к2, часов_назад=3)
        решение = о2.можно_писать_первым()
        проверить(
            f"после {настройки.ПЕРВЫХ_В_СУТКИ} писем за сутки очередь останавливается",
            not решение and "суточный" in решение.причина,
            решение.причина,
        )
        к.закрыть()
        к2.закрыть()
    finally:
        модуль_очереди.сейчас_тихий_час = было


# --- 3. Тихий час --------------------------------------------------------

def проверить_тишину() -> None:
    print(f"\n[3] Тихий час (с {настройки.ТИХО_С}:00 до {настройки.ТИХО_ДО}:00)")

    if настройки.ТИХО_С == настройки.ТИХО_ДО:
        провалы.append("тихий час выключен в .env")
        print(
            "  ПЛОХО   тихий час ВЫКЛЮЧЕН в .env (QUIET_FROM = QUIET_TO).\n"
            "          Ассистент будет писать незнакомым людям ночью — так\n"
            "          аккаунты и блокируют. Верни QUIET_FROM=22, QUIET_TO=9."
        )
        return

    было = модуль_очереди.местное_время
    try:
        for час, ждём in ((23, True), (3, True), (8, True), (9, False), (14, False)):
            модуль_очереди.местное_время = (
                lambda ч=час: datetime(2026, 8, 12, ч, 30, tzinfo=timezone.utc)
            )
            вышло = модуль_очереди.сейчас_тихий_час()
            проверить(
                f"в {час}:30 {'молчим' if ждём else 'пишем'}",
                вышло == ждём,
                f"получилось {вышло}",
            )
    finally:
        модуль_очереди.местное_время = было


# --- 4. Догонялка --------------------------------------------------------

def проверить_догонялку() -> None:
    print("\n[4] Кому мы должны ответ")
    к = новая_картотека()
    к.добавить(1, "один", "Один", "тест", "нужен юрист")
    к.добавить(2, "два", "Два", "тест", "нужен юрист")
    к.добавить(3, "три", "Три", "тест", "нужен юрист")

    положить_сообщение(к, 1, "клиент", часов_назад=0.1)

    положить_сообщение(к, 2, "клиент", часов_назад=0.3)
    положить_сообщение(к, 2, "ассистент", часов_назад=0.2)

    положить_сообщение(к, 3, "клиент", часов_назад=40)

    долги = {д["telegram_id"] for д in к.неотвеченные()}
    проверить("клиент, чьё слово последнее, попадает в долги", 1 in долги)
    проверить("тот, кому уже ответили, не попадает", 2 not in долги)
    проверить("сообщение вчерашней давности не догоняем", 3 not in долги)

    к.обновить(1, статус=У_ЮРИСТА)
    долги = {д["telegram_id"] for д in к.неотвеченные()}
    проверить("клиента, которого ведёт юрист, не трогаем", 1 not in долги)

    к.обновить(1, статус=ВЕДЁТ_АССИСТЕНТ)
    долги = {д["telegram_id"] for д in к.неотвеченные()}
    проверить("а как только юрист отпустил — снова догоняем", 1 in долги)
    к.закрыть()


# --- 5. Заморозка аккаунта ----------------------------------------------

async def проверить_заморозку() -> None:
    print("\n[5] Заморозка при ограничении Telegram")
    from scripts.тренажёр import ПоддельныйTelegram

    import src.ассистент as модуль

    почта = ПоддельныйTelegram()
    модуль.TelegramClient = lambda *а, **к: почта
    настройки.РЕПЕТИЦИЯ = False

    к = новая_картотека()
    к.добавить(7, "семь", "Семь", "тест", "нужен юрист по ДТП")
    а = модуль.Ассистент(к)

    а.заморожен_до = datetime.now(timezone.utc) + timedelta(hours=1)
    await а.написать_первым(к.получить(7))
    проверить(
        "пока аккаунт придержан, первым не пишем",
        len(почта.отправленное) == 0,
        f"всё же ушло {len(почта.отправленное)}",
    )
    проверить(
        "и лид при этом не закрыт — вернёмся к нему позже",
        к.получить(7)["статус"] == НОВЫЙ,
        f"статус стал {к.получить(7)['статус']}",
    )

    а.заморожен_до = datetime.now(timezone.utc) - timedelta(minutes=1)
    проверить(
        "срок заморозки истёк — запрет снят",
        not (а.заморожен_до and datetime.now(timezone.utc) < а.заморожен_до),
    )
    к.закрыть()


