# --- 7. Юрист забирает клиента ------------------------------------------

async def проверить_перехват() -> None:
    print("\n[7] Юрист забирает клиента через карточку")
    from scripts.тренажёр import ПоддельныйTelegram

    import src.ассистент as модуль

    почта = ПоддельныйTelegram()
    модуль.TelegramClient = lambda *а, **к: почта
    настройки.РЕПЕТИЦИЯ = False
    к = новая_картотека()
    к.добавить(9, "девять", "Девять", "тест", "нужен юрист")
    а = модуль.Ассистент(к)

    к.запомнить_карточку(555, 9)
    проверить("карточку узнаём по её сообщению", к.чья_карточка(555) == 9)
    проверить("чужое сообщение карточкой не считаем", к.чья_карточка(777) is None)

    class Кто:
        def __init__(self, username, id):
            self.username = username
            self.id = id

    ящик = настройки.ЯЩИК_USERNAME or "no_justice77"
    проверить(
        "письмо от юриста узнаём по его нику",
        а._это_ящик(Кто(ящик.upper(), 1)),
    )
    проверить(
        "обычного человека за юриста не принимаем",
        not а._это_ящик(Кто("случайный_человек", 2)),
    )

    # Карточка ушла — второй раз слать нельзя, даже если человек пишет ещё
    к.обновить(9, статус=ГОТОВ)
    к.записать_сообщение(9, "клиент", "а когда со мной свяжутся?")
    было = len(почта.отправленное)
    await а.ответить_клиенту(9)
    ушло = почта.отправленное[было:]

    клиенту = [т for кому, т in ушло if кому in ("девять", "9")]
    проверить("после карточки клиенту больше не пишем", not клиенту)
    проверить(
        "но юристу напоминаем, что человек ждёт",
        any("продолжает писать" in т for _, т in ушло),
    )

    было = len(почта.отправленное)
    await а.ответить_клиенту(9)
    проверить(
        "напоминаем один раз, а не на каждое сообщение",
        len(почта.отправленное) == было,
    )
    к.закрыть()


