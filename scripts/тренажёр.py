"""
Тренажёр — прогоняет диалог с ассистентом без Telegram.

Нужен, чтобы проверять редкие ветки поведения (вежливый отказ, «не знаю»,
пауза, преждевременная передача) не дёргая живых людей и не рискуя аккаунтом.
Наружу не уходит ничего: вместо Telegram подставлен поддельный клиент.
Боевую картотеку тоже не трогает — работает на отдельной временной базе.

    python -m scripts.тренажёр            список сценариев
    python -m scripts.тренажёр отказ      один сценарий
    python -m scripts.тренажёр все        все подряд

Сценарии лежат в папке сценарии/ и правятся как обычный текст.
"""

import asyncio
import sys
import tempfile
from pathlib import Path

from src import настройки

ПАПКА_СЦЕНАРИЕВ = настройки.КОРЕНЬ / "сценарии"
ТЕСТОВЫЙ_ID = 999_000_001


# --- поддельный Telegram -------------------------------------------------

class ПоддельноеСообщение:
    def __init__(self, id: int):
        self.id = id


class ПоддельныйTelegram:
    """Ничего не отправляет — только запоминает, что ассистент хотел сказать."""

    def __init__(self):
        self.отправленное: list[tuple[str, str]] = []
        self._счёт = 0

    async def send_message(self, кому, текст, **_):
        self._счёт += 1
        self.отправленное.append((str(кому), текст))
        return ПоддельноеСообщение(self._счёт)

    async def get_input_entity(self, кто):
        return кто


# --- разбор сценария -----------------------------------------------------

class Сценарий:
    def __init__(self, файл: Path):
        self.имя = файл.stem
        self.ожидаем = ""
        self.в_чате = "Нужен юрист, подскажите"
        self.реплики: list[str] = []

        for строка in файл.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if not строка:
                continue
            if строка.startswith("#"):
                тело = строка.lstrip("#").strip()
                ключ, _, значение = тело.partition(":")
                ключ = ключ.strip().lower()
                if ключ == "ожидаем":
                    self.ожидаем = значение.strip()
                elif ключ == "в чате":
                    self.в_чате = значение.strip()
                continue
            self.реплики.append(строка)


def все_сценарии() -> list[Сценарий]:
    if not ПАПКА_СЦЕНАРИЕВ.exists():
        return []
    return [Сценарий(ф) for ф in sorted(ПАПКА_СЦЕНАРИЕВ.glob("*.txt"))]


# --- прогон --------------------------------------------------------------

ЗАВЕРШЁННЫЕ = {"готов", "отказ", "на_паузе", "у_юриста"}


async def прогнать(сценарий: Сценарий) -> bool:
    # Импортируем внутри: подменяем TelegramClient до создания ассистента
    import src.ассистент as модуль
    from src.картотека import Картотека

    почта = ПоддельныйTelegram()
    модуль.TelegramClient = lambda *а, **к: почта

    # Наружу всё равно ничего не уйдёт — клиент поддельный, а полные
    # тексты в режиме репетиции не видны.
    настройки.РЕПЕТИЦИЯ = False

    временная = Path(tempfile.mkdtemp(prefix="тренажёр-")) / "картотека.db"
    картотека = Картотека(str(временная))
    ассистент = модуль.Ассистент(картотека)

    # Запоминаем, какие инструменты модель пробовала вызвать
    попытки: list[str] = []
    настоящий = ассистент._выполнить

    async def перехват(telegram_id, имя, аргументы):
        попытки.append(имя)
        await настоящий(telegram_id, имя, аргументы)

    ассистент._выполнить = перехват

    картотека.добавить(
        telegram_id=ТЕСТОВЫЙ_ID,
        username="test_client",
        имя="Тестовый Клиент",
        чат_источник="тренажёр",
        исходный_текст=сценарий.в_чате,
    )

    print(f"\n{'=' * 70}\nСЦЕНАРИЙ: {сценарий.имя}")
    print(f"в чате написал: {сценарий.в_чате}")
    print(f"ждём в итоге:   {сценарий.ожидаем or '(не задано)'}\n{'-' * 70}")

    было = 0

    адреса_клиента = {"test_client", str(ТЕСТОВЫЙ_ID)}

    def показать_новое():
        nonlocal было
        for кому, текст in почта.отправленное[было:]:
            метка = "асик" if кому in адреса_клиента else "В ЯЩИК ЮРИСТУ"
            отступ = "\n      "
            print(f"  {метка}: {отступ.join(текст.splitlines())}")
        было = len(почта.отправленное)

    await ассистент.написать_первым(картотека.получить(ТЕСТОВЫЙ_ID))
    показать_новое()

    for реплика in сценарий.реплики:
        статус = картотека.получить(ТЕСТОВЫЙ_ID)["статус"]
        if статус in ЗАВЕРШЁННЫЕ:
            print(f"  (разговор уже закончен: {статус}, остальные реплики не нужны)")
            break
        print(f"  клиент: {реплика}")
        картотека.записать_сообщение(ТЕСТОВЫЙ_ID, "клиент", реплика)
        await ассистент.ответить_клиенту(ТЕСТОВЫЙ_ID)
        показать_новое()

    итог = картотека.получить(ТЕСТОВЫЙ_ID)["статус"]
    ответов = sum(
        1 for с in картотека.переписка(ТЕСТОВЫЙ_ID) if с["кто"] == "клиент"
    )
    картотека.закрыть()

    print("-" * 70)
    print(f"итог:      {итог}")
    print(f"ответов клиента: {ответов}, инструменты: {', '.join(попытки) or 'ни одного'}")

    if not сценарий.ожидаем:
        print("вердикт:   — (ожидание не задано)")
        return True

    хорошо = итог == сценарий.ожидаем
    print(f"вердикт:   {'ХОРОШО' if хорошо else 'ПЛОХО — ждали ' + сценарий.ожидаем}")
    return хорошо


async def main():
    сценарии = все_сценарии()
    if not сценарии:
        print(f"Нет сценариев в {ПАПКА_СЦЕНАРИЕВ}")
        return

    аргумент = (sys.argv[1] if len(sys.argv) > 1 else "").strip().lower()

    if not аргумент:
        print("Сценарии:")
        for с in сценарии:
            print(f"  {с.имя:20} → ждём {с.ожидаем or '?'}")
        print("\nЗапуск: python -m scripts.тренажёр <имя>   или   все")
        return

    if аргумент != "все":
        сценарии = [с for с in сценарии if аргумент in с.имя.lower()]
        if not сценарии:
            print(f"Сценарий «{аргумент}» не найден")
            return

    итоги = []
    for с in сценарии:
        итоги.append((с.имя, await прогнать(с)))

    if len(итоги) > 1:
        print(f"\n{'=' * 70}\nСВОДКА")
        for имя, хорошо in итоги:
            print(f"  {'ХОРОШО' if хорошо else 'ПЛОХО '}  {имя}")
        плохих = sum(1 for _, х in итоги if not х)
        print(f"\nвсего {len(итоги)}, плохих {плохих}")


if __name__ == "__main__":
    asyncio.run(main())
